/** The tree page's own text in the language in use; reactive. */
export function tt(key: TreeKey, n?: number): string {
  const lang = language();
  const s = (lang && BY_LANG[lang]?.[key]) || EN[key];
  return n === undefined ? s : s.replace("{n}", String(n));
}
