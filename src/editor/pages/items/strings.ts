type Key = keyof (typeof STRINGS)["en"];

/** What the Items page says itself, in the language in use; reactive. `{n}` takes `n`. */
export function s(key: Key, n?: number): string {
  const lang = language();
  const text: string = (lang && STRINGS[lang as keyof typeof STRINGS]?.[key]) || STRINGS.en[key];
  return n === undefined ? text : text.replace("{n}", String(n));
}
