// Translation for POBT's build screens. Everything Path of Building itself says (stat names, tab names, gem and item
// text, configuration labels) goes through the same dictionary the Lua POB is translated with (trs/<language>), so a
// new league's text is a new row in those CSVs, not code. What only POBT says is in POBT_STRINGS below.
import { signal } from "nsh";
import { Pob } from "pobt/native";

/** The language in use (`trs/<language>`), or null for English. */
export const language = signal<string | null>(null);
/** Bumped when a dictionary loads: what reads `tr` follows it. */
const loaded = signal(0);
const cache = new Map<string, string>();

/** Loads the dictionary of `lang` (null for none). */
export async function useLanguage(lang: string | null) {
  await Pob.trLoad(lang ?? "");
  cache.clear();
  language.set(lang);
  loaded.update((n) => n + 1);
}

function lookup(text: string): string {
  let t = cache.get(text);
  if (t === undefined) {
    t = (JSON.parse(Pob.tr(JSON.stringify([text]))) as string[])[0] ?? text;
    // POB writes many labels with a colon ("Life:"); the dictionary may know only that form
    if (t === text && !text.endsWith(":") && /^[A-Za-z]/.test(text)) {
      const withColon = (JSON.parse(Pob.tr(JSON.stringify([`${text}:`]))) as string[])[0];
      if (withColon && withColon !== `${text}:`) t = withColon.replace(/[:：]\s*$/, "");
    }
    cache.set(text, t);
  }
  return t;
}

/** `text` (English, as Path of Building says it) in the language in use; reactive. */
export function tr(text: string | undefined | null): string {
  loaded();
  if (!text || language() === null) return text ?? "";
  return lookup(text);
}

type PobtKey = keyof (typeof POBT_STRINGS)["en"];

/** What POBT says itself, in the language in use; reactive. */
export function t(key: PobtKey): string {
  const lang = language();
  return (lang && POBT_STRINGS[lang as keyof typeof POBT_STRINGS]?.[key]) || POBT_STRINGS.en[key];
}

