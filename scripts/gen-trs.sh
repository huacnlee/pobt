#!/bin/sh
# Writes src/trs_files.rs: every file under trs/, built into the app so a
# release needs nothing beside its executable. Run it after adding or
# removing translation files (a test checks the list is current).
set -e
cd "$(dirname "$0")/.."
out=src/trs_files.rs
{
  echo "// Generated by scripts/gen-trs.sh from trs/: do not edit."
  echo
  echo "/// The translation files, by their path under \`trs/\`."
  echo "pub static FILES: &[(&str, &[u8])] = &["
  find trs -type f \( -name '*.csv' -o -name '*.json' \) | LC_ALL=C sort | while read -r f; do
    rel=${f#trs/}
    echo "    (\"$rel\", include_bytes!(\"../$f\")),"
  done
  echo "];"
} > "$out"
echo "wrote $out ($(grep -c include_bytes "$out") files)"
